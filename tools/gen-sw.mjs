// Writes www/sw.js with a versioned precache list of the app shell (code, css, fonts, icons).
// Car images are cached on first use, or all at once from Settings → Offline play.
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
const root = new URL('../www/', import.meta.url).pathname;
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const shell = walk(root).map(f => path.relative(root, f)).filter(f => !f.startsWith('assets/') && f !== 'sw.js' && !f.endsWith('.txt')).sort();
const hash = crypto.createHash('sha1'); for (const f of shell) hash.update(fs.readFileSync(path.join(root, f)));
const v = hash.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(root, 'sw.js'), `// GENERATED by tools/gen-sw.mjs
const SHELL = 'beltrun-mobile-shell-${v}', ASSETS = 'beltrun-mobile-assets-v1';
const FILES = ${JSON.stringify(['./', ...shell])};
self.addEventListener('install', e => { e.waitUntil(caches.open(SHELL).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('beltrun-mobile-shell-') && k !== SHELL).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;
  if (u.pathname.includes('/assets/')) {
    e.respondWith(caches.open(ASSETS).then(async c => (await c.match(e.request, { ignoreSearch: true })) || fetch(e.request).then(r => { if (r.ok) c.put(e.request, r.clone()); return r; })));
    return;
  }
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(r => r || fetch(e.request)).catch(() => caches.match('./')));
});
`);
console.log('sw.js', v, shell.length, 'files');
