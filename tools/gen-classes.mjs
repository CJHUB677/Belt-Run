// Precomputes each car's stock robot 1/4-mile ET (used for class assignment) so the game
// doesn't run 67×N simulations at startup. Re-run after changing cars.js or the physics.
import fs from 'node:fs';
import { CARS } from '../www/js/data/cars.js';
import { buildCar, defaultTune } from '../www/js/sim/build.js';
import { simulateRun } from '../www/js/sim/race.js';
const out = {};
for (const car of CARS) {
  let best = Infinity;
  for (let lr = 1500; lr <= car.phys.engine.redline * 0.9; lr += 500) {
    const s = simulateRun(buildCar(car, {}, { ...defaultTune(car), launchRpm: lr }), { nitrous: false }).result.player;
    if (s.et && s.et < best) best = s.et;
  }
  out[car.id] = +best.toFixed(3);
}
fs.writeFileSync(new URL('../www/js/data/stock-et.js', import.meta.url), `// GENERATED by tools/gen-classes.mjs\nexport const STOCK_ET = ${JSON.stringify(out)};\n`);
console.log('stock-et.js written', Object.keys(out).length);
